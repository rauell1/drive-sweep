  const STRINGS = { en: EN, es: ES, fr: FR, de: DE, pt: PT };
  let currentLang = "en";

  function t(key) {
    const pack = STRINGS[currentLang] || EN;
    return pack[key] || EN[key] || key;
  }

  function phrase(text) {
    const pack = PHRASES[currentLang];
    return (pack && pack[text]) || text;
  }

  /* Static English text in index.html marked with data-l (text), data-l-attr (attributes)
     or data-l-init (initial text that app.js replaces later) is translated by phrase. */
  const ORIGINALS = new WeakMap();

  function originalsOf(el) {
    let o = ORIGINALS.get(el);
    if (!o) {
      o = {};
      ORIGINALS.set(el, o);
    }
    return o;
  }

  function applyPhrases() {
    document.querySelectorAll("[data-l]").forEach((el) => {
      const o = originalsOf(el);
      if (o.text === undefined) o.text = el.textContent.trim();
      el.textContent = phrase(o.text);
    });
    document.querySelectorAll("[data-l-init]").forEach((el) => {
      const o = originalsOf(el);
      const current = el.textContent.trim();
      if (o.text === undefined) o.text = current;
      if (current === o.text || current === o.shown) {
        o.shown = phrase(o.text);
        el.textContent = o.shown;
      }
    });
    document.querySelectorAll("[data-l-attr]").forEach((el) => {
      const o = originalsOf(el);
      for (const name of el.getAttribute("data-l-attr").split(",")) {
        const attr = name.trim();
        if (!attr) continue;
        if (o["@" + attr] === undefined) o["@" + attr] = el.getAttribute(attr) || "";
        if (o["@" + attr]) el.setAttribute(attr, phrase(o["@" + attr]));
      }
    });
  }

  function applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const k = el.getAttribute("data-i18n");
      if (k) {
        el.textContent = t(k);
      }
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const k = el.getAttribute("data-i18n-title");
      if (k) {
        el.setAttribute("title", t(k));
      }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const k = el.getAttribute("data-i18n-placeholder");
      if (k) {
        el.setAttribute("placeholder", t(k));
      }
    });
    applyPhrases();
  }

  function setLanguage(lang) {
    currentLang = STRINGS[lang] ? lang : "en";
    applyTranslations();
    return currentLang;
  }

  function getLanguage() {
    return currentLang;
  }

  window.DriveSweepI18n = {
    t,
    phrase,
    STRINGS,
    PHRASES,
    setLanguage,
    getLanguage,
    applyTranslations,
    SUPPORTED: [
      { code: "en", label: "English" },
      { code: "es", label: "Español" },
      { code: "fr", label: "Français" },
      { code: "de", label: "Deutsch" },
      { code: "pt", label: "Português" },
    ],
  };
